import { readFile, writeFile } from 'node:fs/promises';

// EN: ft8js's Emscripten glue loads its .wasm binary via a runtime fetch()
// relative to its own file. That breaks two of this project's targets: the
// single-file portable Web build (no companion files allowed) and Tauri's
// custom protocol origins. Embedding both binaries as base64 lets us hand
// them to the Emscripten module via `wasmBinary` instead, so decoding works
// identically in every build without a network request.
// UK: Emscripten-завантажувач ft8js читає .wasm через fetch() відносно
// свого файлу. Це ламає портативну Web-збірку (без супутніх файлів) і
// кастомні протоколи Tauri. Вбудовуємо обидва бінарники як base64, щоб
// передати їх модулю через `wasmBinary` — без мережевого запиту.
// DE: Der Emscripten-Loader von ft8js lädt seine .wasm-Datei per fetch()
// relativ zur eigenen Datei. Das bricht den portablen Web-Build und
// Tauris Custom-Protocol-Origins. Beide Binärdateien werden als Base64
// eingebettet und über `wasmBinary` übergeben — ganz ohne Netzwerkaufruf.

const decodeWasm = await readFile('node_modules/ft8js/wasm/decode.wasm');
const encodeWasm = await readFile('node_modules/ft8js/wasm/encode.wasm');

const out = `// Auto-generated by scripts/generate-ft8-wasm-assets.mjs — do not edit by hand.
// Regenerate after bumping the ft8js dependency: node scripts/generate-ft8-wasm-assets.mjs

export const FT8_DECODE_WASM_BASE64 = ${JSON.stringify(decodeWasm.toString('base64'))};
export const FT8_ENCODE_WASM_BASE64 = ${JSON.stringify(encodeWasm.toString('base64'))};
`;

await writeFile('src/lib/ft8/wasm-assets.ts', out, 'utf8');
console.log(
  `Wrote src/lib/ft8/wasm-assets.ts (decode: ${decodeWasm.length}B, encode: ${encodeWasm.length}B, base64 total: ${Math.round((decodeWasm.length + encodeWasm.length) * 1.34 / 1024)}KB)`
);
